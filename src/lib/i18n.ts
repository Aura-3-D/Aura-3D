export function t(
  locale: Locale,
  key: keyof Copy,
  vars?: Record<string, string | number>,
): string {
  let out = COPY[locale][key];
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      out = out.replaceAll(`{${name}}`, String(value));
    }
  }
  return out;
}

